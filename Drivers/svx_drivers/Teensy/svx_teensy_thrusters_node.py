# Thrust map helpers (the thrust_map option). Module-level so they can be
# tested without building the node.

def interpolateThrustRows(volts, table, supply_voltage_v):
    # table rows are (pulse_us, kgf at volts[0], kgf at volts[1], ...).
    # Returns [(pulse_us, kgf), ...] at supply_voltage_v: that voltage's own
    # column when it is one of volts, otherwise a linear interpolation between
    # the two neighbouring columns at every row.
    v = float(supply_voltage_v)
    if math.isnan(v) or v < volts[0] or v > volts[-1]:
        raise ValueError("supply_voltage_v " + str(supply_voltage_v) + " is outside the thrust data's " +
                         str(volts[0]) + "-" + str(volts[-1]) + " V")
    if v in volts:
        k = volts.index(v)
        return [(row[0], row[1 + k]) for row in table]
    hi = 1
    while volts[hi] < v:
        hi += 1
    lo = hi - 1
    w = (v - volts[lo]) / (volts[hi] - volts[lo])
    return [(row[0], row[1 + lo] + w * (row[1 + hi] - row[1 + lo])) for row in table]


def buildThrustCurve(rows, stop_us):
    # rows: [(pulse_us, kgf), ...] at one voltage, negative kgf in reverse.
    # Returns the monotone envelopes outward from stop_us -- fwd: from stop_us
    # up, the running maximum of the force; rev: from stop_us down, the running
    # maximum of minus the force -- as [(pulse_us, kgf), ...], and their ends,
    # the full-scale thrust each way. The data dips between neighbouring rows
    # in places, so the map inverts these envelopes, never the raw rows.
    rows = sorted(rows)
    pulses = [row[0] for row in rows]
    if stop_us not in pulses:
        raise ValueError("thrust data has no row at the stop pulse " + str(stop_us) + " us")
    i_stop = pulses.index(stop_us)
    fwd = []
    best = None
    for (pulse, kgf) in rows[i_stop:]:
        best = kgf if best is None else max(best, kgf)
        fwd.append((pulse, best))
    rev = []
    best = None
    for (pulse, kgf) in reversed(rows[:i_stop + 1]):
        best = -kgf if best is None else max(best, -kgf)
        rev.append((pulse, best))
    if fwd[-1][1] <= 0.0 or rev[-1][1] <= 0.0:
        raise ValueError("thrust data has no thrust in one direction")
    return dict(fwd = fwd, rev = rev, fwd_max = fwd[-1][1], rev_max = rev[-1][1])


def thrustToPulse(envelope, thrust_kgf):
    # envelope: one of buildThrustCurve's, outward from stop. Returns the
    # fractional pulse where it reaches thrust_kgf: the first row at or above
    # it, interpolated linearly from the row before, which is below it. Past
    # the last row, the last row's pulse.
    if thrust_kgf <= envelope[0][1]:
        return float(envelope[0][0])
    for k in range(1, len(envelope)):
        if envelope[k][1] >= thrust_kgf:
            (p0, t0) = envelope[k - 1]
            (p1, t1) = envelope[k]
            return p0 + (thrust_kgf - t0) / (t1 - t0) * (p1 - p0)
    return float(envelope[-1][0])


